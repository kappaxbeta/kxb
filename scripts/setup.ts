#!/usr/bin/env bun
/**
 * From a fresh clone to a database worth opening, in one command.
 *
 *   bun install
 *   bun run setup     # this file
 *   bun run dev
 *
 * ---------------------------------------------------------------------------
 * What it does, in order
 * ---------------------------------------------------------------------------
 *   1. Starts the local Supabase stack in Docker if it is not up. A first
 *      `supabase start` applies every migration, which already carries the
 *      catalogue that is schema-shaped: the skins, the tiers, the feature flags,
 *      the contest settings, the Oasis chapter list.
 *   2. Applies any migration the database has not seen. That is the step that
 *      matters after a `git pull` on a database that already exists - `start`
 *      only migrates a database it is creating.
 *   3. Seeds the starter worlds into the world catalogue. Those are content,
 *      generated by code, so they come from `scripts/seed-worlds.ts` rather
 *      than SQL - see the note at the top of that file.
 *   4. Creates a local admin you can sign in as straight away: confirmed,
 *      marked email-verified (so no banner asks for a link that Mailpit would
 *      have to deliver), and a backoffice superadmin, so /ovaloffice opens.
 *
 * Every step is idempotent. Run it again after every pull; it changes nothing
 * that is already right, and resets the admin's password to the one below.
 *
 * ---------------------------------------------------------------------------
 * The admin, and why it is safe to have a default
 * ---------------------------------------------------------------------------
 * `admin@kxb.team` / `test123`, overridable with SETUP_ADMIN_EMAIL and
 * SETUP_ADMIN_PASSWORD. A password that short is only accepted because the
 * local stack's `minimum_password_length` is 6 and the app's forms agree.
 *
 * A known password is only harmless on a database nobody else can reach, so
 * this refuses outright unless `supabase status` reports a loopback API. It
 * reads the stack's URL and keys from the CLI, never from .env or .env.local -
 * the one file that could point it at a hosted project is the one it ignores.
 */

import { $ } from 'bun'
import { createClient } from '@supabase/supabase-js'

// The CLI's analytics flush can time out on exit and report a failure after the
// command succeeded; see scripts/dev.sh for the same line and the same reason.
process.env.DO_NOT_TRACK = '1'

const ADMIN_EMAIL = (process.env.SETUP_ADMIN_EMAIL ?? 'admin@kxb.team').trim().toLowerCase()
const ADMIN_PASSWORD = process.env.SETUP_ADMIN_PASSWORD ?? 'test123'

function step(text: string) {
  console.log(`\n==> ${text}`)
}

function fail(text: string): never {
  console.error(`\n  ${text}\n`)
  process.exit(1)
}

// ---------------------------------------------------------------------------
// 1. The stack
// ---------------------------------------------------------------------------
if ((await $`docker info`.quiet().nothrow()).exitCode !== 0) {
  fail('Docker is not running. The local Supabase stack runs in Docker - start Docker Desktop and retry.')
}

if ((await $`supabase status`.quiet().nothrow()).exitCode !== 0) {
  step('Starting the local Supabase stack (the first run pulls images - be patient)')
  await $`supabase start`
}

// ---------------------------------------------------------------------------
// 2. Migrations the database has not seen
// ---------------------------------------------------------------------------
step('Applying new migrations')
await $`supabase migration up --local --include-all`

// ---------------------------------------------------------------------------
// The stack's own address and key - and the refusal that guards step 4
// ---------------------------------------------------------------------------
const env = Object.fromEntries(
  (await $`supabase status -o env`.quiet().text())
    .split('\n')
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter((m): m is RegExpMatchArray => m !== null)
    .map((m) => [m[1], m[2]]),
)
const apiUrl = env.API_URL
const serviceKey = env.SERVICE_ROLE_KEY
if (!apiUrl || !serviceKey) fail('Could not read the API URL and service key from `supabase status`.')

const host = new URL(apiUrl).hostname
if (!['127.0.0.1', 'localhost', '::1', '[::1]'].includes(host)) {
  fail(`Refusing to seed ${apiUrl}: setup only ever writes to a local stack.`)
}

// ---------------------------------------------------------------------------
// 3. The world catalogue
// ---------------------------------------------------------------------------
step('Seeding the starter worlds')
await $`bun run scripts/seed-worlds.ts`.env({
  ...process.env,
  NEXT_PUBLIC_SUPABASE_URL: apiUrl,
  SUPABASE_SERVICE_ROLE_KEY: serviceKey,
})

// ---------------------------------------------------------------------------
// 4. The local admin
// ---------------------------------------------------------------------------
step(`Creating the local admin ${ADMIN_EMAIL}`)
const admin = createClient(apiUrl, serviceKey, { auth: { persistSession: false, autoRefreshToken: false } })

/**
 * Found by paging rather than by a filter, because the admin API has none for
 * email. A local database has a handful of users; one page is the whole list.
 */
const { data: listed, error: listError } = await admin.auth.admin.listUsers({ perPage: 1000 })
if (listError) fail(`Could not list users: ${listError.message}`)
const existing = listed.users.find((u) => u.email?.toLowerCase() === ADMIN_EMAIL)

/** The mark `src/domain/profile/email-verification.ts` reads. Merged, never replaced. */
const verified = { email_verified_for: ADMIN_EMAIL, email_verified_at: new Date().toISOString() }

if (existing) {
  const { error } = await admin.auth.admin.updateUserById(existing.id, {
    password: ADMIN_PASSWORD,
    email_confirm: true,
    app_metadata: { ...existing.app_metadata, ...verified },
  })
  if (error) fail(`Could not update ${ADMIN_EMAIL}: ${error.message}`)
  console.log('    already there - password reset, marked verified')
} else {
  const { error } = await admin.auth.admin.createUser({
    email: ADMIN_EMAIL,
    password: ADMIN_PASSWORD,
    email_confirm: true,
    app_metadata: verified,
  })
  if (error) fail(`Could not create ${ADMIN_EMAIL}: ${error.message}`)
  console.log('    created')
}

const { error: grantError } = await admin
  .from('backoffice_admins')
  .upsert({ email: ADMIN_EMAIL, note: 'local admin, written by bun run setup' }, { onConflict: 'email' })
if (grantError) fail(`Could not make ${ADMIN_EMAIL} a backoffice admin: ${grantError.message}`)
console.log('    backoffice superadmin')

console.log(`
==> Ready. Now:

    bun run dev

    App      http://127.0.0.1:3000
    Sign in  ${ADMIN_EMAIL} / ${ADMIN_PASSWORD}
    Studio   ${env.STUDIO_URL ?? 'see supabase status'}
    Mailpit  ${env.MAILPIT_URL ?? env.INBUCKET_URL ?? 'see supabase status'}
`)
